//! MAC-PHY control and status register definitions, see TC6 spec Section 9 ("Control and Status
//! Registers").
//!
//! Only Register Memory Map 0 (MMS 0, "Standard Control and Status Registers", spec Section 9.2) is
//! modelled here with per-bit accessors, since that is the only memory map the spec defines down to
//! the bit. MMS 1 (MAC) is implementation-defined, and MMS 2..=6 pass the IEEE 802.3 PHY MMD
//! register spaces through unchanged, so those only get [`mms`] selectors and [`addr`] helpers.
//!
//! Each register is a `u32` newtype matching the on-wire value exactly (control data is always
//! transferred as 32-bit words, spec Section 7.4), with `const fn` getters and `with_*` builders in
//! the same style as [`crate::tc6_header`] / [`crate::tc6_footer`]. The repetitive accessor pairs
//! are generated by the [`define_register!`] tt-muncher so the field list stays in spec bit order.

use crate::bitfield::{get_bit, get_bits, set_bit, set_bits};

/// Memory Map Selector values for the `MMS` field of a control command header (spec Table 6).
pub mod mms {
    /// Standard Control and Status registers (32-bit wide) — the registers modelled in this file.
    pub const STANDARD: u8 = 0x0;
    /// MAC registers. Width and layout are implementation-defined (spec Section 9.3).
    pub const MAC: u8 = 0x1;
    /// PHY PCS registers, IEEE 802.3 MMD 3 (16-bit).
    pub const PHY_PCS: u8 = 0x2;
    /// PHY PMA/PMD registers, IEEE 802.3 MMD 1 (16-bit).
    pub const PHY_PMA_PMD: u8 = 0x3;
    /// PHY vendor specific and PLCA registers, IEEE 802.3 MMD 31 (16-bit).
    pub const PHY_VS_PLCA: u8 = 0x4;
    /// PHY auto-negotiation registers, IEEE 802.3 MMD 7 (16-bit).
    pub const PHY_AUTONEG: u8 = 0x5;
    /// PHY power unit registers, IEEE 802.3 MMD 13 (16-bit).
    pub const PHY_POWER: u8 = 0x6;
}

/// Register addresses within MMS 0 (spec Table 7).
pub mod addr {
    /// Identification Version Register, [`super::IdVer`].
    pub const IDVER: u16 = 0x0000;
    /// PHY Identification Register, [`super::PhyId`].
    pub const PHYID: u16 = 0x0001;
    /// Standard Capabilities Register, [`super::StdCap`].
    pub const STDCAP: u16 = 0x0002;
    /// Reset Control and Status Register, [`super::Reset`].
    pub const RESET: u16 = 0x0003;
    /// Configuration Register #0, [`super::Config0`].
    pub const CONFIG0: u16 = 0x0004;
    /// Configuration Register #1 (reserved).
    pub const CONFIG1: u16 = 0x0005;
    /// Configuration Register #2 (vendor specific).
    pub const CONFIG2: u16 = 0x0006;
    /// Status Register #0, [`super::Status0`].
    pub const STATUS0: u16 = 0x0008;
    /// Status Register #1 (vendor specific).
    pub const STATUS1: u16 = 0x0009;
    /// Buffer Status Register, [`super::BufSts`].
    pub const BUFSTS: u16 = 0x000B;
    /// Interrupt Mask Register #0, [`super::IMask0`].
    pub const IMASK0: u16 = 0x000C;
    /// Interrupt Mask Register #1 (vendor specific).
    pub const IMASK1: u16 = 0x000D;
    /// Transmit Timestamp Capture Register A, high 32 bits (bits 63..32).
    pub const TTSCAH: u16 = 0x0010;
    /// Transmit Timestamp Capture Register A, low 32 bits (bits 31..0).
    pub const TTSCAL: u16 = 0x0011;
    /// Transmit Timestamp Capture Register B, high 32 bits.
    pub const TTSCBH: u16 = 0x0012;
    /// Transmit Timestamp Capture Register B, low 32 bits.
    pub const TTSCBL: u16 = 0x0013;
    /// Transmit Timestamp Capture Register C, high 32 bits.
    pub const TTSCCH: u16 = 0x0014;
    /// Transmit Timestamp Capture Register C, low 32 bits.
    pub const TTSCCL: u16 = 0x0015;

    /// Address of MDIO Access Register `n`, `n` in `0..=7` (spec Section 9.2.19), [`super::MdioAcc`].
    pub const fn mdioacc(n: u8) -> u16 {
        debug_assert!(n < 8, "there are only 8 MDIO access registers (0..=7)");
        0x0020 + n as u16
    }

    /// Address of PHY Clause 22 standard register `reg`, `reg` in `0..=0x1F`
    /// (directly mapped into MMS 0 at `0xFF00..=0xFF1F`).
    pub const fn clause22(reg: u8) -> u16 {
        debug_assert!(reg < 0x20, "Clause 22 register index is 5 bits");
        0xFF00 + reg as u16
    }

    /// Address of PHY Clause 29 (Clause 22 extended) register `reg`, `reg` in `0..=0x1F`
    /// (directly mapped into MMS 0 at `0xFF20..=0xFF3F`).
    pub const fn clause29(reg: u8) -> u16 {
        debug_assert!(reg < 0x20, "Clause 29 register index is 5 bits");
        0xFF20 + reg as u16
    }
}

/// Generate a `u32` newtype register with `const fn` field accessors, in spec bit order.
///
/// Field syntax, one per line inside the braces:
/// * `name, with_name : bool @ POS;` — single bit at `POS`.
/// * `name, with_name : TY @ SHIFT, MASK;` — multi-bit field, `MASK` applied after `>> SHIFT`,
///   value read/written as `TY` (`u8` / `u16` / `u32`).
macro_rules! define_register {
    (
        $(#[$sm:meta])*
        $name:ident { $($fields:tt)* }
    ) => {
        $(#[$sm])*
        #[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
        pub struct $name(u32);

        impl $name {
            /// Wrap a raw 32-bit register value.
            pub const fn from_raw(raw: u32) -> Self {
                Self(raw)
            }

            /// The raw 32-bit register value.
            pub const fn raw(self) -> u32 {
                self.0
            }

            /// Decode from the 4 big-endian bytes as they appear on the wire.
            pub fn from_bytes(bytes: [u8; 4]) -> Self {
                Self(u32::from_be_bytes(bytes))
            }

            /// Encode to the 4 big-endian bytes as they appear on the wire.
            pub fn to_bytes(self) -> [u8; 4] {
                self.0.to_be_bytes()
            }

            define_register!(@fields $($fields)*);
        }
    };

    (@fields) => {};

    (
        @fields
        $(#[$fm:meta])*
        $get:ident, $with:ident : bool @ $pos:literal;
        $($rest:tt)*
    ) => {
        $(#[$fm])*
        pub const fn $get(self) -> bool {
            get_bit(self.0, $pos)
        }
        $(#[$fm])*
        pub const fn $with(self, val: bool) -> Self {
            Self(set_bit(self.0, $pos, val))
        }
        define_register!(@fields $($rest)*);
    };

    (
        @fields
        $(#[$fm:meta])*
        $get:ident, $with:ident : $ty:tt @ $shift:literal, $mask:literal;
        $($rest:tt)*
    ) => {
        $(#[$fm])*
        pub const fn $get(self) -> $ty {
            get_bits(self.0, $shift, $mask) as $ty
        }
        $(#[$fm])*
        pub const fn $with(self, val: $ty) -> Self {
            Self(set_bits(self.0, $shift, $mask, val as u32))
        }
        define_register!(@fields $($rest)*);
    };
}

define_register! {
    /// `IDVER` (0x0000) — Identification Version Register (spec Section 9.2.1, read-only).
    ///
    /// Reports the OPEN Alliance Serial 10BASE-T1x MAC-PHY specification version the device
    /// implements. Reset value is [`IdVer::RESET_VALUE`] (v1.1).
    IdVer {
        /// `MINVER` (bits 3..0) — OPEN Alliance minor version.
        minver, with_minver: u8 @ 0, 0xF;
        /// `MAJVER` (bits 7..4) — OPEN Alliance major version.
        majver, with_majver: u8 @ 4, 0xF;
    }
}

impl IdVer {
    /// Reset value: major version 1, minor version 1.
    pub const RESET_VALUE: Self = Self(0x0000_0011);
}

define_register! {
    /// `PHYID` (0x0001) — PHY Identification Register (spec Section 9.2.2, read-only).
    ///
    /// Same layout as IEEE 802.3 clause 22.2.4.3.1: a 22-bit slice of the manufacturer OUI plus a
    /// model and revision number.
    PhyId {
        /// `REVISION` (bits 3..0) — manufacturer's revision number.
        revision, with_revision: u8 @ 0, 0xF;
        /// `MODEL` (bits 9..4) — manufacturer's model number.
        model, with_model: u8 @ 4, 0x3F;
        /// `OUI` (bits 31..10) — bits 2..23 of the manufacturer's 24-bit Organizationally Unique
        /// Identifier (OUI bit 2 lands at PHYID bit 31, OUI bit 23 at PHYID bit 10).
        oui, with_oui: u32 @ 10, 0x3F_FFFF;
    }
}

define_register! {
    /// `STDCAP` (0x0002) — Standard Capabilities Register (spec Section 9.2.3, read-only).
    ///
    /// Advertises which optional MAC-PHY features this device supports.
    StdCap {
        /// `MINCPS` (bits 2..0) — minimum supported chunk payload size, as `2^MINCPS` bytes
        /// (valid `3..=6`, i.e. 8..64 bytes). See [`StdCap::mincps_bytes`].
        mincps, with_mincps: u8 @ 0, 0x7;
        /// `SEQC` (bit 4) — transmit data header SEQ bit monitoring capability.
        seqc, with_seqc: bool @ 4;
        /// `AIDC` (bit 5) — address increment disable capability (the AID control-header bit).
        aidc, with_aidc: bool @ 5;
        /// `FTSC` (bit 6) — frame timestamp capability.
        ftsc, with_ftsc: bool @ 6;
        /// `CTC` (bit 7) — cut-through (frame) capability.
        ctc, with_ctc: bool @ 7;
        /// `DPRAC` (bit 8) — direct PHY register access capability (PHY regs mapped into SPI space).
        dprac, with_dprac: bool @ 8;
        /// `IPRAC` (bit 9) — indirect PHY register access capability (via the `MDIOACCn` registers).
        iprac, with_iprac: bool @ 9;
        /// `TXFCSVC` (bit 10) — transmit frame check sequence validation capability.
        txfcsvc, with_txfcsvc: bool @ 10;
    }
}

impl StdCap {
    /// Decode [`StdCap::mincps`] into a minimum chunk payload size in bytes (`2^mincps`).
    pub const fn mincps_bytes(self) -> u16 {
        1u16 << self.mincps()
    }
}

define_register! {
    /// `RESET` (0x0003) — Reset Control and Status Register (spec Section 9.2.4).
    Reset {
        /// `SWRESET` (bit 0) — write `1` to fully reset the MAC-PHY (including the integrated PHY).
        /// Self-clearing; the reset does not take effect until CSn is deasserted.
        swreset, with_swreset: bool @ 0;
    }
}

impl Reset {
    /// A `RESET` write that asserts `SWRESET`.
    pub const SWRESET: Self = Self(0x0000_0001);
}

define_register! {
    /// `CONFIG0` (0x0004) — Configuration Register #0 (spec Section 9.2.5).
    ///
    /// Primary MAC-PHY configuration word. Reset value is [`Config0::RESET_VALUE`] (64-byte chunk
    /// payload, everything else clear).
    Config0 {
        /// `CPS` (bits 2..0) — chunk payload size, as `2^CPS` bytes (valid `3..=6`, i.e. 8..64).
        /// Must not change once [`Config0::sync`] has been set. See [`Config0::cps_bytes`].
        cps, with_cps: u8 @ 0, 0x7;
        /// `SEQE` (bit 4) — enable MAC-PHY monitoring of the transmit data header SEQ bit.
        seqe, with_seqe: bool @ 4;
        /// `PROTE` (bit 5) — enable control read/write protection (transfer each word with its
        /// complement for error detection).
        prote, with_prote: bool @ 5;
        /// `FTSS` (bit 6) — frame timestamp select: `0` = 32-bit timestamps, `1` = 64-bit.
        ftss, with_ftss: bool @ 6;
        /// `FTSE` (bit 7) — enable capture of frame ingress/egress timestamps.
        ftse, with_ftse: bool @ 7;
        /// `RXCTE` (bit 8) — receive cut-through enable (network -> SPI host).
        rxcte, with_rxcte: bool @ 8;
        /// `TXCTE` (bit 9) — transmit cut-through enable (SPI host -> network).
        txcte, with_txcte: bool @ 9;
        /// `TXCTHRESH` (bits 11..10) — transmit credit threshold for asserting IRQn.
        /// See [`Config0::txcthresh_credits`].
        txcthresh, with_txcthresh: u8 @ 10, 0x3;
        /// `ZARFE` (bit 12) — zero-align receive frame enable (every frame starts at SWO 0 of some
        /// receive chunk payload).
        zarfe, with_zarfe: bool @ 12;
        /// `CSARFE` (bit 13) — CSn-align receive frame enable (frames start in the first receive
        /// chunk payload after CSn assertion, SWO always 0).
        csarfe, with_csarfe: bool @ 13;
        /// `TXFCSVE` (bit 14) — transmit frame check sequence validation enable.
        txfcsve, with_txfcsve: bool @ 14;
        /// `SYNC` (bit 15) — configuration synchronized. Host sets this once configured; writing `0`
        /// afterwards does not clear it. Mirrored in the receive footer SYNC bit.
        sync, with_sync: bool @ 15;
    }
}

impl Config0 {
    /// Reset value: `CPS` = 6 (64-byte chunk payload), all other fields clear.
    pub const RESET_VALUE: Self = Self(0x0000_0006);

    /// Decode [`Config0::cps`] into a chunk payload size in bytes (`2^cps`).
    pub const fn cps_bytes(self) -> u16 {
        1u16 << self.cps()
    }

    /// Decode [`Config0::txcthresh`] into the minimum number of free transmit credits that must be
    /// available before IRQn is asserted (`1`, `4`, `8` or `16`).
    pub const fn txcthresh_credits(self) -> u8 {
        match self.txcthresh() {
            0b00 => 1,
            0b01 => 4,
            0b10 => 8,
            _ => 16,
        }
    }
}

define_register! {
    /// `STATUS0` (0x0008) — Status Register #0 (spec Section 9.2.8).
    ///
    /// Sticky error/event flags. Every bit except [`Status0::phyint`] is write-1-to-clear; each also
    /// asserts the receive footer EXST bit unless masked in [`IMask0`]. Reset value is
    /// [`Status0::RESET_VALUE`] (`RESETC` set).
    Status0 {
        /// `TXPE` (bit 0) — transmit protocol error (bad transmit data chunk sequence).
        txpe, with_txpe: bool @ 0;
        /// `TXBOE` (bit 1) — transmit buffer overflow error.
        txboe, with_txboe: bool @ 1;
        /// `TXBUE` (bit 2) — transmit buffer underflow error.
        txbue, with_txbue: bool @ 2;
        /// `RXBOE` (bit 3) — receive buffer overflow error (frame data lost).
        rxboe, with_rxboe: bool @ 3;
        /// `LOFE` (bit 4) — loss of framing error (CSn deasserted early).
        lofe, with_lofe: bool @ 4;
        /// `HDRE` (bit 5) — header error (parity check failed on a received header).
        hdre, with_hdre: bool @ 5;
        /// `RESETC` (bit 6) — reset complete: MAC-PHY is out of reset and ready for configuration.
        /// Non-maskable; also holds EXST = 1 in the receive footer until cleared.
        resetc, with_resetc: bool @ 6;
        /// `PHYINT` (bit 7) — physical layer interrupt (service request from the PHY). Read-only;
        /// cleared by acknowledging the underlying PHY interrupt source.
        phyint, with_phyint: bool @ 7;
        /// `TTSCAA` (bit 8) — transmit timestamp capture available in `TTSCAH`/`TTSCAL`.
        ttscaa, with_ttscaa: bool @ 8;
        /// `TTSCAB` (bit 9) — transmit timestamp capture available in `TTSCBH`/`TTSCBL`.
        ttscab, with_ttscab: bool @ 9;
        /// `TTSCAC` (bit 10) — transmit timestamp capture available in `TTSCCH`/`TTSCCL`.
        ttscac, with_ttscac: bool @ 10;
        /// `TXFCSE` (bit 11) — transmit frame check sequence error (host appended an invalid FCS).
        txfcse, with_txfcse: bool @ 11;
        /// `CDPE` (bit 12) — control data protection error (bad protected control write data).
        cdpe, with_cdpe: bool @ 12;
    }
}

impl Status0 {
    /// Reset value: `RESETC` set, everything else clear.
    pub const RESET_VALUE: Self = Self(0x0000_0040);

    /// Mask of all currently defined, non-reserved status bits (bits 12..0).
    pub const DEFINED_MASK: u32 = 0x0000_1FFF;

    /// A write-1-to-clear value that acknowledges every defined status bit.
    pub const fn clear_all() -> Self {
        Self(Self::DEFINED_MASK)
    }
}

define_register! {
    /// `BUFSTS` (0x000B) — Buffer Status Register (spec Section 9.2.10, read-only).
    ///
    /// Snapshot of the transmit-credit and receive-chunk counters. Both fields also appear
    /// (saturated to 5 bits) in every receive data footer.
    BufSts {
        /// `RCA` (bits 7..0) — receive chunks available: additional receive data chunks the host
        /// may read right now.
        rca, with_rca: u8 @ 0, 0xFF;
        /// `TXC` (bits 15..8) — transmit credits available: consecutive transmit data chunks the
        /// host may write without overflowing the MAC.
        txc, with_txc: u8 @ 8, 0xFF;
    }
}

define_register! {
    /// `IMASK0` (0x000C) — Interrupt Mask Register #0 (spec Section 9.2.11).
    ///
    /// Setting a bit to `1` prevents the matching [`Status0`] bit from asserting the receive footer
    /// EXST bit. Reset value is [`IMask0::RESET_VALUE`] (everything masked except the non-maskable
    /// `RESETCM`). Field names mirror [`Status0`] with an `M` suffix.
    IMask0 {
        /// `TXPEM` (bit 0) — mask for [`Status0::txpe`].
        txpem, with_txpem: bool @ 0;
        /// `TXBOEM` (bit 1) — mask for [`Status0::txboe`].
        txboem, with_txboem: bool @ 1;
        /// `TXBUEM` (bit 2) — mask for [`Status0::txbue`].
        txbuem, with_txbuem: bool @ 2;
        /// `RXBOEM` (bit 3) — mask for [`Status0::rxboe`].
        rxboem, with_rxboem: bool @ 3;
        /// `LOFEM` (bit 4) — mask for [`Status0::lofe`].
        lofem, with_lofem: bool @ 4;
        /// `HDREM` (bit 5) — mask for [`Status0::hdre`].
        hdrem, with_hdrem: bool @ 5;
        /// `RESETCM` (bit 6) — read-only `0`; `RESETC` is non-maskable and always asserts IRQn.
        resetcm, with_resetcm: bool @ 6;
        /// `PHYINTM` (bit 7) — mask for [`Status0::phyint`].
        phyintm, with_phyintm: bool @ 7;
        /// `TTSCAAM` (bit 8) — mask for [`Status0::ttscaa`].
        ttscaam, with_ttscaam: bool @ 8;
        /// `TTSCABM` (bit 9) — mask for [`Status0::ttscab`].
        ttscabm, with_ttscabm: bool @ 9;
        /// `TTSCACM` (bit 10) — mask for [`Status0::ttscac`].
        ttscacm, with_ttscacm: bool @ 10;
        /// `TXFCSEM` (bit 11) — mask for [`Status0::txfcse`].
        txfcsem, with_txfcsem: bool @ 11;
        /// `CDPEM` (bit 12) — mask for [`Status0::cdpe`].
        cdpem, with_cdpem: bool @ 12;
    }
}

impl IMask0 {
    /// Reset value: all maskable interrupts masked (`RESETCM` reads `0`).
    pub const RESET_VALUE: Self = Self(0x0000_1FBF);
}

